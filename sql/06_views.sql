USE BIBLIOTECA_DB;

-- 1. Vista amigable de préstamos
CREATE OR REPLACE VIEW VW_PRESTAMOS_DETALLE AS
SELECT 
    p.FECHA_P AS FechaPrestamo,
    CONCAT(e.NOMBRES, ' ', e.APELLIDOS) AS Estudiante,
    l.TITULO AS TituloLibro,
    CONCAT(f.NOMBRES, ' ', f.APELLIDOS) AS Funcionario,
    car.NOMBRE AS CarreraEstudiante
FROM PRESTAMO p
INNER JOIN ESTUDIANTES e ON p.RUT_EST = e.RUT_EST
INNER JOIN LIBROS l ON p.COD_LIBRO = l.COD_LIBRO
INNER JOIN FUNCIONARIOS f ON p.RUT_FUNC = f.RUT_FUNC
INNER JOIN CARRERAS car ON e.ID_CARRERA = car.ID_CARRERA;

-- 2. Vista de libros por biblioteca
CREATE OR REPLACE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT 
    b.BIBLIOTECA AS NombreBiblioteca,
    COUNT(l.COD_LIBRO) AS TotalLibros
FROM BIBLIOTECA b
LEFT JOIN LIBROS l ON b.ID_BIBLIO = l.ID_BIBLIO
GROUP BY b.ID_BIBLIO, b.BIBLIOTECA;