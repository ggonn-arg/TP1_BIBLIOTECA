USE BIBLIOTECA_DB;

-- Tabla previa para auditoría
CREATE TABLE IF NOT EXISTS AUDITORIA_PRESTAMOS (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    RUT_EST VARCHAR(20) NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_REGISTRO DATETIME NOT NULL,
    ACCION VARCHAR(50) NOT NULL
);

-- 1. Trigger de auditoría post inserción
DELIMITER //
CREATE TRIGGER TR_AUDITAR_PRESTAMO
AFTER INSERT ON PRESTAMO
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_PRESTAMOS (RUT_EST, COD_LIBRO, FECHA_REGISTRO, ACCION)
    VALUES (NEW.RUT_EST, NEW.COD_LIBRO, NOW(), 'NUEVO PRÉSTAMO');
END //
DELIMITER ;

-- 2. Trigger para validar edad mínima (menores a 17 años no permitidos)
DELIMITER //
CREATE TRIGGER TR_VALIDAR_EDAD_ESTUDIANTE
BEFORE INSERT ON ESTUDIANTES
FOR EACH ROW
BEGIN
    IF NEW.EDAD < 17 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Error: El estudiante debe ser mayor de edad para registrarse.';
    END IF;
END //
DELIMITER ;