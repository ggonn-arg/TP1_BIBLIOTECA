CREATE DATABASE IF NOT EXISTS BIBLIOTECA_DB;
USE BIBLIOTECA_DB;

-- 1. Tablas catálogo / independientes
CREATE TABLE CIUDAD (
    ID_CIUDAD INT AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    PRIMARY KEY (ID_CIUDAD)
);

CREATE TABLE AUTORES (
    RUT_AUTOR VARCHAR(20),
    NOMBRES VARCHAR(50) NOT NULL,
    APELLIDOS VARCHAR(50) NOT NULL,
    PRIMARY KEY (RUT_AUTOR)
);

CREATE TABLE EDITORIALES (
    ID_EDIT INT AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    PAIS VARCHAR(50) NOT NULL,
    PRIMARY KEY (ID_EDIT)
);

CREATE TABLE TIPO (
    ID_TIPO INT AUTO_INCREMENT,
    TIPO_P VARCHAR(50) NOT NULL,
    PRIMARY KEY (ID_TIPO)
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIO INT AUTO_INCREMENT,
    BIBLIOTECA VARCHAR(100) NOT NULL,
    PRIMARY KEY (ID_BIBLIO)
);

-- 2. Tablas de Sedes y Carreras
CREATE TABLE CAMPUS (
    ID_CAMPUS INT AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    PRIMARY KEY (ID_CAMPUS),
    FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE CARRERAS (
    ID_CARRERA INT AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    PRIMARY KEY (ID_CARRERA),
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE FUNCIONARIOS (
    RUT_FUNC VARCHAR(20),
    NOMBRES VARCHAR(50) NOT NULL,
    APELLIDOS VARCHAR(50) NOT NULL,
    EDAD INT,
    DIRECCION VARCHAR(150),
    SALUD VARCHAR(50) DEFAULT 'Buena',
    ID_CAMPUS INT NOT NULL,
    PRIMARY KEY (RUT_FUNC),
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE ESTUDIANTES (
    RUT_EST VARCHAR(20),
    NOMBRES VARCHAR(50) NOT NULL,
    APELLIDOS VARCHAR(50) NOT NULL,
    EDAD INT,
    FONO VARCHAR(20),
    DIRECCION VARCHAR(150),
    ID_CARRERA INT NOT NULL,
    PRIMARY KEY (RUT_EST),
    FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
);

-- 3. Libros y Préstamos
CREATE TABLE LIBROS (
    COD_LIBRO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AGNO INT NOT NULL,
    ID_BIBLIO INT NOT NULL,
    ID_TIPO INT NOT NULL,
    RUT_AUTOR VARCHAR(20) NOT NULL,
    ID_EDIT INT NOT NULL,
    PRIMARY KEY (COD_LIBRO),
    FOREIGN KEY (ID_BIBLIO) REFERENCES BIBLIOTECA(ID_BIBLIO),
    FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO),
    FOREIGN KEY (RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR),
    FOREIGN KEY (ID_EDIT) REFERENCES EDITORIALES(ID_EDIT)
);

CREATE TABLE PRESTAMO (
    RUT_EST VARCHAR(20),
    RUT_FUNC VARCHAR(20),
    COD_LIBRO INT,
    FECHA_P DATE NOT NULL,
    FECHA_E DATE,
    PRIMARY KEY (RUT_EST, RUT_FUNC, COD_LIBRO, FECHA_P),
    FOREIGN KEY (RUT_EST) REFERENCES ESTUDIANTES(RUT_EST),
    FOREIGN KEY (RUT_FUNC) REFERENCES FUNCIONARIOS(RUT_FUNC),
    FOREIGN KEY (COD_LIBRO) REFERENCES LIBROS(COD_LIBRO)
);